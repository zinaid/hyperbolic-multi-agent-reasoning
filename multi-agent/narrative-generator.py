# Narrative generation
def generate_story(father_path, mother_path, son_path, lexicon):

    paths = [
        father_path,
        mother_path,
        son_path,
    ]

    story_chunks = []

    for path in paths:

        level_1_key = (
            path[1].split("_", 1)[1]
            if "_" in path[1]
            else path[1]
        )

        level_2_key = (
            path[2].split("_", 1)[1]
            if "_" in path[2]
            else path[2]
        )

        level_3_key = path[3].lower()

        sentences = [
            lexicon.get(level_1_key, ""),
            lexicon.get(level_2_key, ""),
            lexicon.get(level_3_key, ""),
        ]

        sentences = [
            sentence
            for sentence in sentences
            if sentence
        ]

        story_chunks.append(" ".join(sentences))

    return "\n\n".join(story_chunks)


